// Writes src/shared/engine-tables.ts: the host and path lists that the content
// scripts' cheap pre-filters need, taken from the tables safetycatch-engine
// exports (PLATFORMS, DEVICE_CODE_ENDPOINTS, OAUTH_ENDPOINTS). The content
// scripts cannot import the engine itself (it would put about 270 KB into every
// page), so they get this small generated copy. `pnpm run build` regenerates it
// and a unit test fails when the file in the repository is out of date.
//
//   node scripts/engine-tables.ts            rewrite the file
//   node scripts/engine-tables.ts --check    exit 1 when it is out of date

import { DEVICE_CODE_ENDPOINTS, OAUTH_ENDPOINTS, PLATFORMS } from 'safetycatch-engine';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const TABLES_FILE = fileURLToPath(new URL('../src/shared/engine-tables.ts', import.meta.url));

interface Endpoint {
  host?: string;
  hostRe?: RegExp;
  paths: readonly string[];
}

export function engineTablesSource(): string {
  // Plain literals only (no function calls), so the bundler can leave the tables out of a
  // script that does not use them (the sub-frame script).
  const platforms: string[] = [];
  const seen = new Set<string>();
  for (const p of PLATFORMS) {
    for (const host of p.hosts) {
      const entry = JSON.stringify([host.toLowerCase(), ...(p.paths ?? []).map((x) => x.toLowerCase())]);
      if (seen.has(entry)) continue;
      seen.add(entry);
      platforms.push(`  ${entry},`);
    }
  }
  const auth: string[] = [];
  for (const e of [...DEVICE_CODE_ENDPOINTS, ...OAUTH_ENDPOINTS] as readonly Endpoint[]) {
    const paths = JSON.stringify(e.paths.map((x) => x.toLowerCase()));
    if (e.host) auth.push(`  { host: ${JSON.stringify(e.host.toLowerCase())}, paths: ${paths} },`);
    else if (e.hostRe) auth.push(`  { hostRe: /${e.hostRe.source}/${e.hostRe.flags}, paths: ${paths} },`);
  }
  return `// Copyright 2026 The SafetyCatch Authors
// SPDX-License-Identifier: Apache-2.0
//
// GENERATED by scripts/engine-tables.ts from the tables safetycatch-engine
// exports. Do not edit by hand; \`pnpm run build\` rewrites it.

/** User-content platforms (engine \`PLATFORMS\`): host, then the path prefixes that hold user content (none: the whole host). */
export const PLATFORM_HINTS: ReadonlyArray<readonly [string, ...string[]]> = [
${platforms.join('\n')}
];

/** Device-code and app-approval sign-in pages (engine \`DEVICE_CODE_ENDPOINTS\` and \`OAUTH_ENDPOINTS\`); \`{tenant}\` is one path segment. */
export const AUTH_HINTS: ReadonlyArray<{ readonly host?: string; readonly hostRe?: RegExp; readonly paths: readonly string[] }> = [
${auth.join('\n')}
];
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const want = engineTablesSource();
  let have = '';
  try {
    have = readFileSync(TABLES_FILE, 'utf8');
  } catch {
    have = '';
  }
  if (process.argv.includes('--check')) {
    if (have !== want) {
      console.error('src/shared/engine-tables.ts is out of date. Run: node scripts/engine-tables.ts');
      process.exit(1);
    }
  } else if (have !== want) {
    writeFileSync(TABLES_FILE, want);
    console.log('wrote src/shared/engine-tables.ts');
  }
}
